const fs = require('fs');
const path = require('path');

const booksDir = path.join(__dirname, '..', 'books');
const dataDir = path.join(__dirname, '..', 'data');

if (!fs.existsSync(dataDir)) {
  fs.mkdirSync(dataDir, { recursive: true });
}

function scanBooks() {
  const manifest = {};
  if (!fs.existsSync(booksDir)) return manifest;

  const bookFolders = fs.readdirSync(booksDir, { withFileTypes: true })
    .filter(d => d.isDirectory())
    .map(d => d.name);

  bookFolders.forEach(bookId => {
    manifest[bookId] = {};
    const bookPath = path.join(booksDir, bookId);
    const langFolders = fs.readdirSync(bookPath, { withFileTypes: true })
      .filter(d => d.isDirectory())
      .map(d => d.name);

    langFolders.forEach(lang => {
      const langPath = path.join(bookPath, lang);
      const interiorsPath = path.join(langPath, 'interiors');

      // Detect cover
      let cover = null;
      ['cover.png', 'cover.webp', 'cover.jpg', 'cover.jpeg'].forEach(file => {
        if (!cover && fs.existsSync(path.join(langPath, file))) {
          cover = `books/${bookId}/${lang}/${file}`;
        }
      });

      // Detect back cover
      let back = null;
      ['back.png', 'back.webp', 'back.jpg', 'back.jpeg'].forEach(file => {
        if (!back && fs.existsSync(path.join(langPath, file))) {
          back = `books/${bookId}/${lang}/${file}`;
        }
      });

      // Detect interiors
      const interiors = [];
      if (fs.existsSync(interiorsPath)) {
        const files = fs.readdirSync(interiorsPath)
          .filter(f => /\.(png|webp|jpe?g)$/i.test(f))
          .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));

        files.forEach(f => {
          interiors.push(`books/${bookId}/${lang}/interiors/${f}`);
        });
      }

      manifest[bookId][lang] = {
        cover,
        back,
        interiors,
        pageCount: (cover ? 1 : 0) + interiors.length + (back ? 1 : 0)
      };
    });
  });

  return manifest;
}

function generate() {
  const manifest = scanBooks();

  // Output JSON
  fs.writeFileSync(
    path.join(dataDir, 'books-manifest.json'),
    JSON.stringify(manifest, null, 2),
    'utf8'
  );

  // Output JS for static usage without fetch requirement
  fs.writeFileSync(
    path.join(dataDir, 'books-manifest.js'),
    `// Auto-generated by scripts/generate-books-manifest.js\nwindow.BOOKS_MANIFEST = ${JSON.stringify(manifest, null, 2)};\nif (typeof module !== 'undefined') module.exports = window.BOOKS_MANIFEST;\n`,
    'utf8'
  );

  console.log(`✅ Manifest generato con successo per ${Object.keys(manifest).length} libri in data/books-manifest.json e data/books-manifest.js`);
  return manifest;
}

if (require.main === module) {
  generate();
}

module.exports = { generate, scanBooks };
